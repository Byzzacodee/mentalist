/**
 * UI language system: RU / UZ / EN.
 * Persisted in LocalStorage. AI output language is set via
 * languageDirective() injected into every system prompt.
 */

export const LANGUAGES = [
  { id: 'ru', label: 'РУС', ai: 'русском языке' },
  { id: 'uz', label: 'UZB', ai: "o'zbek tili" },
  { id: 'en', label: 'ENG', ai: 'English language' },
];

const K = 'mentalist.lang';

export function getLang() {
  try {
    return localStorage.getItem(K) || 'ru';
  } catch {
    return 'ru';
  }
}

export function setLang(l) {
  try {
    localStorage.setItem(K, l);
  } catch {
    /* noop */
  }
}

export function langName(id) {
  return (LANGUAGES.find((l) => l.id === id) || LANGUAGES[0]).ai;
}

